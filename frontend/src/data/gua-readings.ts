/** 一卦的编写层内容。原文（卦辞 / 爻辞 / 出处 URL）在 `data/gua.ts`，此处一律不放。 */
export interface GuaReading {
  /** 通行本卦序，与 `data/gua.ts` 的 `order` 同一口径。 */
  order: GuaOrder;
  /**
   * 卦名，**逐字取自 `data/gua.ts` 的 `name`**（该字段是 gua.ts 的**派生层**，简体，与全站一致；
   * gua.ts 的 `guaName` 才是保留源文用字的原文层，本文件不引它）。
   * ⚠️ 仅供人工复核与对表（一眼看出这段配的是哪一卦），**页面显示的卦名以 `data/gua.ts` 为准**，
   * 不要从这里取值渲染——两处取值会给「改一处忘另一处」留口子。
   */
  nameHint: string;
  /**
   * 卦名训解的**引用回显** —— `quote` / `work` 逐字取自 `data/gua.ts` 的
   * `nameGloss` / `nameGlossWork`，**属引用层，不是本项目的主张**。
   *
   * 为什么在编写层文件里冗余存一份：`vernacular` 是一整串成文的话，训解被**嵌在句子中间**，
   * 光靠读字符串没法机器核对它是否仍与 `gua.ts` 一致。存成结构化字段后，测试可以断言
   * ① `quote`/`work` === `gua.ts` 对应值；② `vernacular` 同时包含这两者。
   * 上一轮 `nameHint` 因 `gua.ts` 改用字而**静默失效 48/64**，就是缺这道断言的代价。
   *
   * ⚠️ **三卦刻意没有这一栏**：无妄(25) / 大過(28) / 明夷(36) —— `gua.ts` 里就没有训解，
   * 三源（序卦 / 雜卦 / 彖傳）给的都带判词或倾覆义，宁可整段留白也不去别处凑。
   * 取值时必须判 `undefined`。
   */
  nameGloss?: { readonly quote: string; readonly work: string };
  /** 白话疏解，本项目编写。措辞见文件头「写法」。 */
  vernacular: string;
  /** 这段用到的《说卦》取象词，供验收逐条回溯（PRD §16-19）。 */
  imagerySource: readonly ShuoguaWord[];
  /** true = 未定稿的示例占位，页面须显示「示例（占位）」（CLAUDE.md §7 / PRD §8.4-3）。 */
  placeholder: boolean;
}

